import React, { useState } from 'react';
import {
  Settings,
  Sliders,
  RotateCcw,
  Volume2,
  VolumeX,
  HardDrive,
  ShieldAlert,
  CheckCircle2,
  Trash2,
  Cpu,
  Clock,
  Sparkles,
} from 'lucide-react';
import { useTraffic } from '../../context/TrafficContext';
import { soundManager } from '../../services/soundEffects';

export const SettingsView: React.FC = () => {
  const {
    settings,
    updateSettings,
    clearPackets,
    resetAllData,
    packets,
  } = useTraffic();

  const [notification, setNotification] = useState<string>('');

  const showNotification = (msg: string) => {
    setNotification(msg);
    setTimeout(() => setNotification(''), 3000);
  };

  const handleSpeedChange = (e: React.ChangeEvent<HTMLInputElement>) => {
    updateSettings({ simulationSpeed: parseInt(e.target.value, 10) });
  };

  const handleBufferLimitChange = (limit: number) => {
    updateSettings({ bufferLimit: limit });
    showNotification(`Buffer capacity set to ${limit} packets.`);
  };

  const handleTestAudio = () => {
    soundManager.playAlert('High');
    showNotification('Played alert sound preview.');
  };

  return (
    <div className="space-y-6 max-w-4xl">
      {/* Top Banner */}
      <div className="bg-slate-900/90 border border-slate-800 rounded-xl p-5 flex items-center justify-between">
        <div className="flex items-center gap-3">
          <div className="p-2 rounded-lg bg-emerald-500/10 border border-emerald-500/30 text-emerald-400">
            <Settings className="w-5 h-5" />
          </div>
          <div>
            <h2 className="font-mono text-base font-bold text-slate-100">
              ANALYZER ENGINE SETTINGS &amp; LOCAL STORAGE
            </h2>
            <p className="text-xs text-slate-400">
              Configure packet telemetry simulation rates, IDS thresholds, and client persistence
            </p>
          </div>
        </div>
      </div>

      {notification && (
        <div className="p-3 rounded-lg bg-cyan-950/60 border border-cyan-500/40 text-cyan-200 text-xs font-mono flex items-center gap-2">
          <CheckCircle2 className="w-4 h-4 text-cyan-400 shrink-0" />
          <span>{notification}</span>
        </div>
      )}

      {/* 1. Simulation Speed & Frequency */}
      <div className="bg-slate-900/80 border border-slate-800 rounded-xl p-5 space-y-4 font-mono text-xs">
        <div className="flex items-center justify-between border-b border-slate-800 pb-3">
          <div className="flex items-center gap-2">
            <Clock className="w-4 h-4 text-cyan-400" />
            <h3 className="font-semibold text-slate-200 text-sm">SIMULATED PACKET STREAM SPEED</h3>
          </div>
          <span className="text-cyan-400 font-bold">
            {(1000 / settings.simulationSpeed).toFixed(2)} packets/sec ({settings.simulationSpeed} ms/pkt)
          </span>
        </div>

        <p className="text-slate-400 text-[11px] leading-relaxed">
          Adjust the packet arrival frequency generated by the client-side stochastic engine. Lower values simulate high-density gigabit LAN saturation.
        </p>

        <div className="space-y-2">
          <input
            type="range"
            min="250"
            max="3000"
            step="150"
            value={settings.simulationSpeed}
            onChange={handleSpeedChange}
            className="w-full accent-cyan-400 bg-slate-800 h-2 rounded-lg cursor-pointer"
          />
          <div className="flex justify-between text-[10px] text-slate-500">
            <span>Fast (4 pkts/sec)</span>
            <span>Normal (1 pkt/sec)</span>
            <span>Slow (0.33 pkts/sec)</span>
          </div>
        </div>
      </div>

      {/* 2. Buffer Capacity & Memory Retention */}
      <div className="bg-slate-900/80 border border-slate-800 rounded-xl p-5 space-y-4 font-mono text-xs">
        <div className="flex items-center justify-between border-b border-slate-800 pb-3">
          <div className="flex items-center gap-2">
            <Cpu className="w-4 h-4 text-emerald-400" />
            <h3 className="font-semibold text-slate-200 text-sm">IN-MEMORY PACKET BUFFER CAPACITY</h3>
          </div>
          <span className="text-emerald-400 font-bold">{settings.bufferLimit} Max Packets</span>
        </div>

        <p className="text-slate-400 text-[11px] leading-relaxed">
          Maximum number of frames retained concurrently in browser memory for real-time charting. Oldest packets are popped when capacity is reached.
        </p>

        <div className="grid grid-cols-4 gap-2">
          {[100, 300, 500, 1000].map((limit) => (
            <button
              key={limit}
              onClick={() => handleBufferLimitChange(limit)}
              className={`py-2 px-3 rounded-lg border text-center transition-colors ${
                settings.bufferLimit === limit
                  ? 'bg-emerald-500/20 border-emerald-500/40 text-emerald-300 font-bold'
                  : 'bg-slate-950 border-slate-800 text-slate-400 hover:text-slate-200'
              }`}
            >
              {limit} Packets
            </button>
          ))}
        </div>
      </div>

      {/* 3. Rule-Based Heuristic IDS Thresholds */}
      <div className="bg-slate-900/80 border border-slate-800 rounded-xl p-5 space-y-4 font-mono text-xs">
        <div className="flex items-center justify-between border-b border-slate-800 pb-3">
          <div className="flex items-center gap-2">
            <ShieldAlert className="w-4 h-4 text-rose-400" />
            <h3 className="font-semibold text-slate-200 text-sm">HEURISTIC IDS DETECTION THRESHOLDS</h3>
          </div>
          <span className="text-[10px] text-slate-400 bg-slate-800 px-2 py-0.5 rounded">Detection Tuning</span>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
          <div className="bg-slate-950 p-3 rounded-lg border border-slate-800">
            <div className="flex justify-between items-center mb-1">
              <span className="text-slate-300 font-semibold">Port Scan Sensitivity</span>
              <span className="text-cyan-400 font-bold">{settings.portScanThreshold} ports</span>
            </div>
            <p className="text-[10px] text-slate-500 mb-2">
              Minimum distinct ports probed by a single IP before triggering RULE_PORT_SCAN_RECONNAISSANCE.
            </p>
            <input
              type="range"
              min="3"
              max="10"
              value={settings.portScanThreshold}
              onChange={(e) => updateSettings({ portScanThreshold: parseInt(e.target.value, 10) })}
              className="w-full accent-cyan-400 bg-slate-800 h-1.5 rounded cursor-pointer"
            />
          </div>

          <div className="bg-slate-950 p-3 rounded-lg border border-slate-800">
            <div className="flex justify-between items-center mb-1">
              <span className="text-slate-300 font-semibold">Traffic Spike Rate Limit</span>
              <span className="text-amber-400 font-bold">{settings.trafficSpikeThreshold} pkts</span>
            </div>
            <p className="text-[10px] text-slate-500 mb-2">
              Burst packet count from single source IP within sliding observation window triggering volume alert.
            </p>
            <input
              type="range"
              min="6"
              max="30"
              value={settings.trafficSpikeThreshold}
              onChange={(e) => updateSettings({ trafficSpikeThreshold: parseInt(e.target.value, 10) })}
              className="w-full accent-amber-400 bg-slate-800 h-1.5 rounded cursor-pointer"
            />
          </div>
        </div>
      </div>

      {/* 4. Audio Alerts & Web Audio Synthesizer */}
      <div className="bg-slate-900/80 border border-slate-800 rounded-xl p-5 space-y-4 font-mono text-xs">
        <div className="flex items-center justify-between border-b border-slate-800 pb-3">
          <div className="flex items-center gap-2">
            <Volume2 className="w-4 h-4 text-cyan-400" />
            <h3 className="font-semibold text-slate-200 text-sm">SECURITY ALERTS AUDIO NOTIFICATIONS</h3>
          </div>
          <span className="text-slate-400 text-[10px]">Web Audio API</span>
        </div>

        <div className="flex items-center justify-between">
          <div>
            <div className="font-semibold text-slate-200">Synthesized Sonar Alert Ping</div>
            <p className="text-[11px] text-slate-400">
              Plays an audio ping whenever a High or Critical security heuristic rule triggers.
            </p>
          </div>
          <div className="flex items-center gap-2">
            <button
              onClick={handleTestAudio}
              className="px-2.5 py-1 rounded bg-slate-800 hover:bg-slate-700 text-slate-300 text-xs border border-slate-700"
            >
              Test Sound
            </button>
            <button
              onClick={() => updateSettings({ soundAlerts: !settings.soundAlerts })}
              className={`px-3 py-1 rounded-lg border font-bold text-xs transition-colors ${
                settings.soundAlerts
                  ? 'bg-emerald-500/20 border-emerald-500/40 text-emerald-300'
                  : 'bg-slate-800 border-slate-700 text-slate-500'
              }`}
            >
              {settings.soundAlerts ? 'ENABLED' : 'MUTED'}
            </button>
          </div>
        </div>
      </div>

      {/* 5. Local Storage & Data Reset */}
      <div className="bg-slate-900/80 border border-slate-800 rounded-xl p-5 space-y-4 font-mono text-xs">
        <div className="flex items-center justify-between border-b border-slate-800 pb-3">
          <div className="flex items-center gap-2">
            <HardDrive className="w-4 h-4 text-purple-400" />
            <h3 className="font-semibold text-slate-200 text-sm">STORAGE &amp; DEMO DATA CONTROLS</h3>
          </div>
          <span className="text-slate-400 text-[10px]">Client Persistence</span>
        </div>

        <p className="text-slate-400 text-[11px] leading-relaxed">
          Network analysis telemetry and configuration parameters are cached in your local browser storage (<code className="text-slate-300">localStorage</code>) to maintain state between page refreshes without needing an external database.
        </p>

        <div className="flex items-center gap-3 pt-1 flex-wrap">
          <button
            onClick={() => {
              clearPackets();
              showNotification('Buffer cleared. Ready for fresh capture.');
            }}
            className="px-3 py-2 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 border border-slate-700 flex items-center gap-1.5 transition-colors"
          >
            <Trash2 className="w-3.5 h-3.5 text-amber-400" />
            <span>Flush Packet Buffer</span>
          </button>

          <button
            onClick={() => {
              resetAllData();
              showNotification('Reset all settings, thresholds, and restored initial seed dataset.');
            }}
            className="px-3.5 py-2 rounded-lg bg-rose-950/40 hover:bg-rose-900/50 text-rose-300 border border-rose-500/40 flex items-center gap-1.5 transition-colors"
          >
            <RotateCcw className="w-3.5 h-3.5 text-rose-400" />
            <span>Reset Everything to Default Factory State</span>
          </button>
        </div>
      </div>
    </div>
  );
};
